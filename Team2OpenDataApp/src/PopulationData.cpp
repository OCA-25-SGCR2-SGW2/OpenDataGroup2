//-----------------------------------------------------------------------------
//	都道府県名から人口を取得する関数
//-----------------------------------------------------------------------------
int PopulationData::GetPopulation(const std::u8string& prefecture) {
	auto it = population_data_.find(prefecture);
	if (it != population_data_.end()) {
		return it->second;
	}
	return 0; // 見つからない場合は0を返す
}

//-----------------------------------------------------------------------------
//	人口の多い順にソートされた都道府県リストを取得
//-----------------------------------------------------------------------------
std::vector<std::pair<std::u8string, int>> PopulationData::GetSortedByPopulation() {
	std::vector<std::pair<std::u8string, int>> sorted_data(
		population_data_.begin(), 
		population_data_.end()
	);
	
	// 人口の降順でソート
	std::sort(sorted_data.begin(), sorted_data.end(),
		[](const auto& a, const auto& b) {
			return a.second > b.second;
		}
	);
	
	return sorted_data;
}

//-----------------------------------------------------------------------------
//	検索結果数と人口から比率を計算する関数（10万人あたり）
//-----------------------------------------------------------------------------
double PopulationData::CalculateRatioPerPopulation(int result_count, const std::u8string& prefecture) {
	int population = GetPopulation(prefecture);
	if (population == 0) {
		return 0.0; // 人口が0の場合は0を返す
	}
	// 10万人あたりの検索結果数を計算
	return (static_cast<double>(result_count) / population) * 100000.0;
}