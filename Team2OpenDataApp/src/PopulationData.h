#include <string>
#include <unordered_map>
#include <vector>

//-----------------------------------------------------------------------------
//	都道府県別人口データを管理するクラス
//-----------------------------------------------------------------------------
class PopulationData {
public:
	//-----------------------------------------------------------------------------
	//!	@brief	都道府県別人口データを初期化する関数
	//-----------------------------------------------------------------------------
	static void Init();
	
	//-----------------------------------------------------------------------------
	//!	@brief	都道府県名から人口を取得する関数
	//! @param	prefecture [in] 都道府県名
	//! @return	人口（人）、見つからない場合は0
	//-----------------------------------------------------------------------------
	static int GetPopulation(const std::u8string& prefecture);
	
	//-----------------------------------------------------------------------------
	//!	@brief	全都道府県の人口データを取得する関数
	//! @return	都道府県名と人口のマップ
	//-----------------------------------------------------------------------------
	static std::unordered_map<std::u8string, int> GetAllPopulationData() { return population_data_; }
	
	//-----------------------------------------------------------------------------
	//!	@brief	人口の多い順にソートされた都道府県リストを取得
	//! @return	都道府県名と人口のペアのベクター（降順）
	//-----------------------------------------------------------------------------
	static std::vector<std::pair<std::u8string, int>> GetSortedByPopulation();

	//-----------------------------------------------------------------------------
	//!	@brief	検索結果数と人口から比率を計算する関数（10万人あたり）
	//! @param	result_count [in] 検索結果数
	//! @param	prefecture [in] 都道府県名
	//! @return	10万人あたりの検索結果数
	//-----------------------------------------------------------------------------
	static double CalculateRatioPerPopulation(int result_count, const std::u8string& prefecture);

private:
	static std::unordered_map<std::u8string, int> population_data_; // 都道府県別人口データ
	static std::unordered_map<std::u8string, double> ratio_data_;   // 都道府県別比率データ
};